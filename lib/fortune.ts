export function kotodamaOf(personSeed: string): Kotodama {
  // 数秘術の還元計算: ハッシュの各桁を1桁になるまで足す（11/22/33は残す）
  let n = hashOf(personSeed, "kotodama") % 100000;
  while (n > 9 && n !== 11 && n !== 22 && n !== 33) {
    n = String(n).split("").reduce((a, c) => a + Number(c), 0);
  }
  return KOTODAMA_NUMBERS.find((k) => k.n === n) ?? KOTODAMA_NUMBERS[0];
}

