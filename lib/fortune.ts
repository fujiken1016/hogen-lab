// ---------- 決定論ハッシュ ----------
function hashOf(seed: string, key: string): number {
  const s = seed + "|" + key;
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
  return h;
}
function pick<T>(arr: T[], seed: string, key: string): T {
  return arr[hashOf(seed, key) % arr.length];
}
function range(seed: string, key: string, min: number, max: number): number {
  return min + (hashOf(seed, key) % (max - min + 1));
}

