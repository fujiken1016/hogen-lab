// ---------- 鑑定結果の組み立て ----------
export type Kantei = {
  kotodama: Kotodama;
  gogyo: Gogyo;
  tarot: TarotCard;
  isUp: boolean; // タロット正位置か
  moon: MoonPhase;
  categories: CategoryFortune[];
  totalN: number;
  opener: string;
  wave: number[]; // 7日間の運気（1〜5）
  bestDayOffset: number; // 勝負日（今日から何日後か）
  direction: { dir: string; tip: string };
  action: string;
};

export function kanteiOf(personSeed: string, dateSeed: string, dialect: string): Kantei {
  const daySeed = dateSeed + "@" + personSeed; // 人×日付
  const kotodama = kotodamaOf(personSeed);
  const gogyo = GOGYO[DIALECT_GOGYO[dialect] ?? "火"];
  const tarot = pick(TAROT, daySeed, "tarot");
  const isUp = hashOf(daySeed, "tarot-dir") % 3 !== 0; // 正位置2/3・逆位置1/3
  const moon = pick(MOON_PHASES, dateSeed, "moon"); // 月相は日付のみ（全員同じ月を見る）
  const cats: CategoryFortune[] = [
    { label: "恋愛運", icon: "💘", n: range(daySeed, "love", 1, 5), text: "" },
    { label: "仕事運", icon: "💼", n: range(daySeed, "work", 1, 5), text: "" },
    { label: "金運", icon: "💰", n: range(daySeed, "money", 1, 5), text: "" },
    { label: "対人運", icon: "🤝", n: range(daySeed, "human", 1, 5), text: "" },
  ];
  const keys = ["love", "work", "money", "human"];
  cats.forEach((c, i) => (c.text = CATEGORY_TEXTS[keys[i]][c.n - 1]));
  const totalN = Math.max(1, Math.min(5, Math.round(cats.reduce((a, c) => a + c.n, 0) / cats.length)));
  const wave = Array.from({ length: 7 }, (_, i) => range(daySeed, `wave${i}`, 1, 5));
  wave[0] = totalN; // 今日の値は総合運と一致させる
  const bestDayOffset = wave.indexOf(Math.max(...wave));
  return {
    kotodama,
    gogyo,
    tarot,
    isUp,
    moon,
    categories: cats,
    totalN,
    opener: OVERALL_OPENERS[totalN - 1],
    wave,
    bestDayOffset,
    direction: pick(DIRECTIONS, daySeed, "dir"),
    action: pick(KAIUN_ACTIONS, daySeed, "action"),
  };
}
