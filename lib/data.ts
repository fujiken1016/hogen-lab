// localStorageへの安全な書込（プライベートモード・容量超過でも落ちない）
export function lsSet(key: string, value: unknown): void {
  try {
    localStorage.setItem(key, JSON.stringify(value));
  } catch {}
}

// 壊れたlocalStorage値でも落ちない安全なJSON読取（配列想定）
export function safeParseArray<T>(raw: string | null): T[] {
  try {
    const v = raw == null ? [] : JSON.parse(raw);
    return Array.isArray(v) ? (v as T[]) : [];
  } catch {
    return [];
  }
}

export function unlockBadge(id: string) {
  if (typeof window === "undefined") return;
  const cur = safeParseArray<string>(localStorage.getItem("hogen_badges"));
  if (!cur.includes(id)) {
    cur.push(id);
    lsSet("hogen_badges", cur);
  }
}

export function getBadges(): string[] {
  if (typeof window === "undefined") return [];
  return safeParseArray<string>(localStorage.getItem("hogen_badges"));
}

// ---------- ユーティリティ ----------
export function shuffle<T>(arr: T[]): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

// ---------- 自由入力の照合（診断で「どれも違う」とき） ----------
function normalizePhrase(s: string): string {
  return s.replace(/[、。！？!?\s〜ー・]/g, "");
}

function bigrams(s: string): string[] {
  const out: string[] = [];
  for (let i = 0; i < s.length - 1; i++) out.push(s.slice(i, i + 2));
  return out;
}

// バイグラムDice係数（0〜1）
export function phraseSimilarity(a: string, b: string): number {
  const A = bigrams(normalizePhrase(a));
  const B = bigrams(normalizePhrase(b));
  if (A.length === 0 || B.length === 0) return 0;
  const rest = [...B];
  let hit = 0;
  for (const g of A) {
    const i = rest.indexOf(g);
    if (i >= 0) {
      hit++;
      rest.splice(i, 1);
    }
  }
  return (2 * hit) / (A.length + B.length);
}

// 語幹らしき形に落とす（投げる→投げ）
// 表示用の「実質同じ言い方」判定。
// バイグラム類似だけだと「こえ〜」vs「あー、こえー」(0.67)のように
// 感動詞の前置きで薄まってすり抜けるため、前置きを剥がした芯の包含もみる。
export function phraseNearDup(a: string, b: string): boolean {
  if (phraseSimilarity(a, b) >= 0.65) return true;
  const core = (s: string) => normalizePhrase(s).replace(/^(あ+|は+|ん+|も+う?|お+い?)/, "");
  const ca = core(a);
  const cb = core(b);
  return ca.length >= 2 && cb.length >= 2 && (ca.includes(cb) || cb.includes(ca));
}

function stem(word: string): string {
  return word.length >= 3 ? word.replace(/[るいうくすつ]$/, "") : word;
}

export type PhraseMatch = { dialect: string; phrase: string; score: number };

// 入力文を全方言の診断フレーズ＋語彙と照合し、近い順に返す
export function matchShindanPhrase(input: string, questionKey: string): PhraseMatch[] {
  const normInput = normalizePhrase(input);
  return Object.entries(SHINDAN_PHRASES)
    .map(([dialect, phrases]) => {
      const phrase = phrases[questionKey] ?? "";
      let score = phraseSimilarity(input, phrase);
      // その方言の語彙が入力に含まれていれば強いシグナル
      for (const w of wordsOf(dialect)) {
        const s = stem(normalizePhrase(w.word.replace(/^〜/, "")));
        if (s.length >= 2 && normInput.includes(s)) {
          score += 0.5;
          break;
        }
      }
      return { dialect, phrase, score };
    })
    .sort((a, b) => b.score - a.score);
}

